import { describe, expect, it, vi } from "vitest";
import { openPullRequest, ProtectedBranchError } from "./delivery.js";
import { GitHubApiError } from "./errors.js";

const baseInput = {
  token: "t",
  owner: "acme",
  repo: "web",
  head: "factory/session-1",
  base: "main",
  title: "feat: add login",
  body: "Generated by the factory",
};

describe("openPullRequest", () => {
  it("opens a pull request", async () => {
    const fetchImpl = vi.fn(
      async () =>
        new Response(
          JSON.stringify({ number: 42, html_url: "https://github.com/acme/web/pull/42" }),
          {
            status: 201,
          },
        ),
    );

    await expect(openPullRequest({ ...baseInput, fetchImpl })).resolves.toEqual({
      number: 42,
      url: "https://github.com/acme/web/pull/42",
    });
  });

  it("returns the existing PR when GitHub reports a duplicate", async () => {
    const fetchImpl = vi
      .fn()
      .mockResolvedValueOnce(new Response("duplicate", { status: 422 }))
      .mockResolvedValueOnce(
        new Response(
          JSON.stringify([{ number: 7, html_url: "https://github.com/acme/web/pull/7" }]),
          { status: 200 },
        ),
      );

    await expect(openPullRequest({ ...baseInput, fetchImpl })).resolves.toEqual({
      number: 7,
      url: "https://github.com/acme/web/pull/7",
    });
    expect(fetchImpl).toHaveBeenCalledTimes(2);
  });

  it("refuses to open a PR from main", async () => {
    await expect(
      openPullRequest({ ...baseInput, head: "main", fetchImpl: vi.fn() }),
    ).rejects.toBeInstanceOf(ProtectedBranchError);
  });

  it("throws a typed error when GitHub fails", async () => {
    const fetchImpl = vi.fn(async () => new Response("nope", { status: 500 }));
    await expect(openPullRequest({ ...baseInput, fetchImpl })).rejects.toBeInstanceOf(
      GitHubApiError,
    );
  });
});
